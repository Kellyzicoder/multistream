const { chromium } = require('playwright-core');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1400, height: 900 }, deviceScaleFactor: 1 });
  p.on('dialog', d => { console.log('dialog:', d.message()); d.accept(); });
  await p.goto('http://127.0.0.1:3917/'); await p.waitForTimeout(2500);
  await p.evaluate(() => { const w = document.getElementById('welcome'); if (w) w.classList.remove('open'); });
  const rows = await p.$$eval('#chList .cc, .cc', els => els.map(e => e.querySelector('.nm') && e.querySelector('.nm').textContent + ' pen=' + !!e.querySelector('.ed')));
  console.log(rows);
  const row = p.locator('.cc', { hasText: 'Kelv Studio' }).first();
  await row.screenshot({ path: process.argv[2] + '/row.png' });
  await row.locator('.ed').click(); await p.waitForTimeout(400);
  await p.locator('.mdl > div').screenshot({ path: process.argv[2] + '/modal.png' });
  await p.fill('.mdl .e1', 'Kelv Studio Sunday live'); await p.click('.mdl .o'); await p.waitForTimeout(800);
  console.log(await p.evaluate(() => fetch('/api/state').then(r => r.json()).then(s => JSON.stringify(s.facebook.also))));
  await p.locator('.cc', { hasText: 'Kelv Studio' }).first().locator('.ed').click(); await p.waitForTimeout(300);
  console.log('title in box:', await p.inputValue('.mdl .e1'));
  await p.click('.mdl .rm'); await p.waitForTimeout(800);
  console.log(await p.evaluate(() => fetch('/api/state').then(r => r.json()).then(s => JSON.stringify(s.facebook.also))));
  await b.close();
})();
